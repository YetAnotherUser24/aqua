#!/usr/bin/env bash
# =============================================================================
# aqua-station host preparation and install
# =============================================================================
# Target: Raspberry Pi 3 Model B+ / Debian GNU/Linux 13 (trixie) / aarch64
# Verified on the actual board: 4 cores, 905 MB RAM, 29.2 GB SD (14.35 GiB
# unallocated when this was written), timezone Europe/London (WRONG for this
# project), 51.5 C idle, and `vcgencmd get_throttled` = 0x50000 meaning that
# under-voltage AND throttling have already occurred.
#
# Run as the `aqua` user with sudo available. Idempotent: safe to re-run.
#
# Usage:
#   sudo ./deploy/install.sh              # full install
#   sudo ./deploy/install.sh --check      # report host state, change nothing
# =============================================================================

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INSTALL_ROOT="/opt/aqua-station"
DATA_ROOT="/data/telemetry"
EXPORT_ROOT="/data/exports"
STATE_ROOT="/var/lib/aqua-gateway"
WEB_ROOT="/srv/aqua-web"
CONF_ROOT="/etc/aqua"
AQUA_USER="aqua"
TIMEZONE="America/Lima"

CHECK_ONLY=0
[[ "${1:-}" == "--check" ]] && CHECK_ONLY=1

# -- output helpers -----------------------------------------------------------
alert()  { printf '\033[31m%s\033[0m\n' "$*"; }
green()  { printf '\033[32m%s\033[0m\n' "$*"; }
yellow() { printf '\033[33m%s\033[0m\n' "$*"; }
section() { printf '\n\033[1;36m== %s ==\033[0m\n' "$*"; }
ok()     { printf '  \033[32mok\033[0m    %s\n' "$*"; }
warn()   { printf '  \033[33mwarn\033[0m  %s\n' "$*"; }
bad()    { printf '  \033[31mfail\033[0m  %s\n' "$*"; }
skip()   { printf '  \033[90mskip\033[0m  %s\n' "$*"; }

FAILURES=0
WARNINGS=0
# Set by configure_mosquitto when it generates the broker credentials, so
# install_gateway can put the gateway's own credential into its env file.
GATEWAY_MQTT_SECRET=""
# Set by configure_postgres when it sets the role's password, for the same reason.
GATEWAY_DB_PASSWORD=""
note_fail() { FAILURES=$((FAILURES + 1)); bad "$*"; }
note_warn() { WARNINGS=$((WARNINGS + 1)); warn "$*"; }

# Where every generated credential is recorded.
#
# These secrets cannot be recovered later: mosquitto stores only hashes, and the
# gateway's database password is set once and never shown again. An earlier version
# of this script merely *printed* them, so the originals were lost the moment the
# terminal scrollback was -- and a node that needs one has no way to get it back.
# Anything this script generates is therefore written here as it is created.
CREDENTIALS_FILE="$CONF_ROOT/mqtt-node-credentials"

record_credential() {
	local key=$1 value=$2

	if [[ ! -f "$CREDENTIALS_FILE" ]]; then
		install -d -m 0755 "$CONF_ROOT"
		# Created with its final mode, so there is no instant where it is readable.
		install -m 0600 -o root -g root /dev/null "$CREDENTIALS_FILE"
		{
			printf '# Generated by deploy/install.sh on %s\n' "$(date -Is)"
			printf '# MQTT node credentials and the gateway database password.\n'
			printf '# The broker keeps only hashes, so this file is the only copy: back it up,\n'
			printf '# and put each node credential in that node firmware build.\n'
		} >>"$CREDENTIALS_FILE"
	fi

	printf '%s=%s\n' "$key" "$value" >>"$CREDENTIALS_FILE"
	chown root:root "$CREDENTIALS_FILE"
	chmod 0600 "$CREDENTIALS_FILE"
}

# =============================================================================
# 0. Preflight — things that must be fixed by a human, not by this script
# =============================================================================
preflight() {
	section "Preflight"

	if [[ "$(uname -m)" != "aarch64" ]]; then
		note_warn "architecture is $(uname -m), expected aarch64"
	fi

	if [[ ! -f /etc/debian_version ]]; then
		note_fail "not a Debian system"
	fi

	local mem_mb
	mem_mb=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
	if ((mem_mb < 800)); then
		note_fail "only ${mem_mb} MB RAM; the tuned stack expects ~900 MB"
	else
		ok "RAM ${mem_mb} MB"
	fi

	# -- rootfs expansion -----------------------------------------------------
	# The board was flashed from a 16 GB image onto a 32 GB card, and the root
	# partition was never grown: 14.35 GiB of the card was unallocated. Verify,
	# because this changes the free-space calculation that retention depends on.
	local disk_bytes part_bytes free_gib
	disk_bytes=$(lsblk -b -ndo SIZE /dev/mmcblk0 2>/dev/null || echo 0)
	part_bytes=$(lsblk -b -ndo SIZE /dev/mmcblk0p2 2>/dev/null || echo 0)
	free_gib=$(df -BG --output=avail / | tail -1 | tr -dc '0-9')

	if ((disk_bytes > 0 && part_bytes > 0)); then
		local unallocated_gib=$(((disk_bytes - part_bytes) / 1024 / 1024 / 1024))
		if ((unallocated_gib > 1)); then
			note_warn "${unallocated_gib} GiB of the SD card is UNALLOCATED"
			printf '         fix with:  sudo raspi-config --expand-rootfs && sudo reboot\n'
			printf '         then re-run this script. Free space would go from %sGB to ~24GB.\n' "$free_gib"
		else
			ok "rootfs expanded (free ${free_gib}GB)"
		fi
	fi

	if ((free_gib < 8)); then
		note_warn "only ${free_gib}GB free on /"
	fi

	# -- power quality --------------------------------------------------------
	# 0x50000 = bit 16 (under-voltage occurred) + bit 18 (throttling occurred).
	# This matters more than SD wear: a brown-out corrupts a running database and
	# can brick a card. Telemetry says a better PSU is the highest-value fix here.
	if command -v vcgencmd >/dev/null 2>&1; then
		local throttled
		throttled=$(vcgencmd get_throttled)
		if [[ "$throttled" =~ throttled=0x0$ ]]; then
			ok "no throttling or under-voltage recorded"
		else
			note_warn "$throttled"
			printf '         Under-voltage has occurred. Replace the PSU (5.1V / 2.5A) and\n'
			printf '         consider a UPS. This is a bigger risk than SD wear.\n'
		fi
	fi

	# -- HAT hardware check (I2C & RTC) ---------------------------------------
	if [[ -e /dev/i2c-1 ]]; then
		ok "I2C bus 1 present (/dev/i2c-1)"
	else
		note_warn "I2C bus 1 not found (/dev/i2c-1) — enable dtparam=i2c_arm=on in /boot/firmware/config.txt"
	fi

	if [[ -e /dev/rtc0 || -e /dev/rtc ]]; then
		ok "Hardware RTC present ($(readlink -f /dev/rtc 2>/dev/null || echo '/dev/rtc0'))"
	else
		note_warn "Hardware RTC (/dev/rtc0) not active — verify dtoverlay=i2c-rtc,ds3231 in /boot/firmware/config.txt"
	fi

	if ((CHECK_ONLY)); then
		section "Check complete"
		printf 'failures=%d warnings=%d\n' "$FAILURES" "$WARNINGS"
		exit 0
	fi
}

# =============================================================================
# 1. Packages
# =============================================================================
install_packages() {
	section "Packages"

	# All confirmed present in Debian 13 arm64 — no third-party repositories.
	# Note what is NOT installed: no Node runtime. The dashboard is a static export
	# served by Caddy, so the Pi needs no JavaScript runtime at all.
	# Also no TimescaleDB: with 5 Hz confined to 3-hour experiment windows, the
	# capacity problem it solves no longer exists (see docs/ARCHITECTURE.md).
	local packages=(
		postgresql-17
		mosquitto
		mosquitto-clients
		caddy
		python3-venv
		python3-pip
		sqlite3
		gzip
		chrony
		avahi-daemon
		i2c-tools
	)

	apt-get update -qq
	apt-get install -y --no-install-recommends "${packages[@]}"
	ok "installed: ${packages[*]}"
}

# =============================================================================
# 2. Host hygiene — timezone and the SD write problem
# =============================================================================
host_hygiene() {
	section "Host hygiene"

	# -- timezone -------------------------------------------------------------
	# The board was on Europe/London while the project is defined in America/Lima.
	# Retention, rotation and the flush timer all key off local midnight, so this
	# is a correctness requirement, not a preference.
	local current
	current=$(timedatectl show -p Timezone --value)
	if [[ "$current" == "$TIMEZONE" ]]; then
		ok "timezone already ${TIMEZONE}"
	else
		timedatectl set-timezone "$TIMEZONE"
		ok "timezone ${current} -> ${TIMEZONE}"
	fi

	# -- the SD write problem -------------------------------------------------
	# Measured idle on this board with NO application running:
	#   7 write ops / 120 sectors / 61,440 bytes in 16 s
	#   => ~0.44 write ops/s => ~38,000 write ops/day, ~330 MB/day
	# Two logging stacks were writing: journald (Storage=persistent) AND rsyslog.
	# The whole telemetry archive needs ~58 write ops/day. Idle logging therefore
	# costs roughly 650x more SD writes than the data pipeline it supports.
	install -D -m 0644 "$REPO_ROOT/deploy/journald/10-aqua-volatile.conf" \
		/etc/systemd/journald.conf.d/10-aqua-volatile.conf
	systemctl restart systemd-journald
	ok "journald pinned to RAM"

	if systemctl is-enabled --quiet rsyslog 2>/dev/null; then
		systemctl disable --now rsyslog
		ok "rsyslog disabled (was double-writing every log line)"
	else
		skip "rsyslog already disabled"
	fi

	# Disabling rsyslog leaves its logrotate fragment behind, and that fragment's postrotate
	# runs `/usr/lib/rsyslog/rsyslog-rotate` unconditionally:
	#
	#     systemctl kill -s HUP --kill-whom=main rsyslog.service
	#     -> Failed to kill unit rsyslog.service: Unit rsyslog.service not loaded
	#
	# A non-zero postrotate aborts the *entire* logrotate run, not just that file, so every
	# other rotated log on the host stops rotating too -- mosquitto's and postgresql's
	# included -- and all that is visible is `logrotate.service: failed` with nothing
	# pointing at rsyslog. journald holds /dev/log on Debian 13, so there is no syslog to
	# signal and the guard is the whole fix; the same shape mosquitto's own fragment uses
	# (`invoke-rc.d mosquitto status`). Only rewrite the stock file, and keep the original
	# beside it, so a hand-edited fragment is not silently replaced.
	if [[ -f /etc/logrotate.d/rsyslog ]] && ! grep -q "is-active --quiet rsyslog.service" /etc/logrotate.d/rsyslog; then
		[[ -f /etc/logrotate.d/rsyslog.orig ]] || cp /etc/logrotate.d/rsyslog /etc/logrotate.d/rsyslog.orig
		cat > /etc/logrotate.d/rsyslog <<'LOGROTATE'
/var/log/syslog
/var/log/mail.log
/var/log/kern.log
/var/log/auth.log
/var/log/user.log
/var/log/cron.log
{
	rotate 4
	weekly
	missingok
	notifempty
	compress
	delaycompress
	sharedscripts
	postrotate
		# rsyslog is disabled on this host (see install.sh, host_hygiene), so there is no
		# daemon to signal. Without this guard the unguarded script above exits non-zero
		# and aborts the whole logrotate run, which stops *every* log on the host from
		# rotating -- including mosquitto's and postgresql's. journald owns /dev/log here
		# (/run/systemd/journal/dev-log), so the syslog socket nothing is listening on is
		# expected, not a fault.
		if systemctl is-active --quiet rsyslog.service; then
			/usr/lib/rsyslog/rsyslog-rotate
		fi
	endscript
}
LOGROTATE
		ok "rsyslog logrotate guarded (an unguarded postrotate was aborting every rotation)"
	else
		skip "rsyslog logrotate already guarded (or absent)"
	fi

	# -- mount options --------------------------------------------------------
	# noatime was already set on this board. Verify rather than assume; without it
	# every file read buys a metadata write.
	local opts
	opts=$(findmnt -no OPTIONS /)
	if [[ "$opts" == *noatime* ]]; then
		ok "root mounted noatime"
	else
		note_warn "root is not mounted noatime (options: $opts)"
	fi

	# -- swap -----------------------------------------------------------------
	# zram swap is already configured and unused. Confirm no SD-backed swapfile
	# exists: swap on SD is the worst possible write pattern.
	if [[ -f /etc/dphys-swapfile ]] && grep -qE '^CONF_SWAPFILE=' /etc/dphys-swapfile; then
		local swapfile
		swapfile=$(grep -E '^CONF_SWAPFILE=' /etc/dphys-swapfile | cut -d= -f2)
		if [[ -f "$swapfile" ]]; then
			note_warn "SD-backed swap file present at $swapfile — disable dphys-swapfile"
		fi
	fi

	# -- RTC DS3231 and I2C hygiene -------------------------------------------
	# Ensure kernel module i2c-dev loads on boot
	if [[ ! -f /etc/modules-load.d/i2c-dev.conf ]]; then
		echo "i2c-dev" > /etc/modules-load.d/i2c-dev.conf
		modprobe i2c-dev 2>/dev/null || true
		ok "i2c-dev module load configured"
	else
		modprobe i2c-dev 2>/dev/null || true
		ok "i2c-dev module load already present"
	fi

	# Allow the aqua service user to access I2C devices without root
	if getent group i2c >/dev/null 2>&1; then
		usermod -a -G i2c "$AQUA_USER"
		ok "user $AQUA_USER added to i2c group"
	fi

	# fake-hwclock periodically writes to SD and restores on boot, overwriting the
	# authoritative DS3231 RTC clock with an outdated shutdown timestamp.
	if systemctl is-enabled --quiet fake-hwclock 2>/dev/null || [[ -f /etc/fake-hwclock.data ]]; then
		systemctl disable --now fake-hwclock 2>/dev/null || true
		apt-get purge -y fake-hwclock 2>/dev/null || true
		ok "fake-hwclock disabled and purged (DS3231 RTC is authoritative)"
	else
		skip "fake-hwclock absent or disabled"
	fi

	# Configure Chrony to synchronize system time to RTC (rtcsync)
	if [[ -d /etc/chrony/conf.d ]]; then
		echo "rtcsync" > /etc/chrony/conf.d/10-rtc.conf
		systemctl restart chrony 2>/dev/null || true
		ok "chrony rtcsync configured"
	fi
}

# =============================================================================
# 3. Directories
# =============================================================================
create_directories() {
	section "Directories"

	# The archive lives on the SD card root filesystem. It is append-only,
	# block-buffered and never fsync'd during normal operation, so its write
	# profile is far gentler than a database's.
	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$DATA_ROOT"
	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$STATE_ROOT"
	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$DATA_ROOT/unknown"
	# Bundles live outside the archive so they can be pruned independently: the raw CSV
	# is the record of what happened, a bundle is a derived convenience for analysis.
	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$EXPORT_ROOT"
	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$(dirname "$WEB_ROOT")"
	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$CONF_ROOT"

	for role in od_sensor aerator mixer pump events unknown; do
		install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$DATA_ROOT/$role"
	done
	ok "created $DATA_ROOT $STATE_ROOT"
}

# =============================================================================
# 4. PostgreSQL
# =============================================================================
configure_postgres() {
	section "PostgreSQL"

	# The shipped defaults assume a machine far larger than this and land at
	# roughly 200 MB resident. Tuned, it sits around 50-80 MB.
	install -D -m 0644 "$REPO_ROOT/deploy/postgres/conf.d/10-aqua.conf" \
		/etc/postgresql/17/main/conf.d/10-aqua.conf
	ok "applied memory tuning (shared_buffers=48MB, jit=off)"

	systemctl enable --now postgresql
	systemctl restart postgresql

	# Wait for the cluster to accept connections, and diagnose it when it will not.
	# `systemctl restart postgresql` returns as soon as the *wrapper* unit is up; the
	# server itself is `postgresql@17-main`, so an invalid setting leaves the wrapper
	# "active" while the cluster is down. Without this check the next psql fails with
	# "No such file or directory" against the socket, naming neither the cluster nor the
	# file at fault -- which is how `stats_temp_storage`, removed in PostgreSQL 15, got
	# as far as a live install before its actual cause was visible.
	local ready=0
	for _ in $(seq 1 30); do
		if pg_isready -q 2>/dev/null; then ready=1; break; fi
		sleep 1
	done
	if ((ready == 0)); then
		note_fail "PostgreSQL is not accepting connections after 30s"
		systemctl --no-pager status postgresql@17-main 2>&1 | tail -12 || true
		printf '\n'
		tail -20 /var/log/postgresql/postgresql-17-main.log || true
		exit 1
	fi
	ok "cluster is accepting connections"

	local db_exists
	db_exists=$(sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='aqua'")
	if [[ "$db_exists" != "1" ]]; then
		sudo -u postgres createuser --no-superuser --no-createdb --no-createrole "$AQUA_USER" || true
		sudo -u postgres createdb -O "$AQUA_USER" aqua
		ok "created database 'aqua'"
	else
		skip "database 'aqua' exists"
	fi

	# The gateway reaches PostgreSQL over TCP (the DSN in .env.example is
	# 127.0.0.1:5432), and the packaged pg_hba requires scram-sha-256 for host
	# connections. `createuser` sets no password, so without this the gateway can never
	# authenticate -- and the failure is disguised twice over: the gateway only logs
	# "database unavailable", and asyncpg probes for a client certificate first, so the
	# visible error is a permission problem on ~/.postgresql/postgresql.key rather than
	# "password authentication failed".
	local has_password
	has_password=$(sudo -u postgres psql -tAc \
		"SELECT rolpassword IS NOT NULL FROM pg_authid WHERE rolname='$AQUA_USER'")
	if [[ "$has_password" != "t" ]]; then
		GATEWAY_DB_PASSWORD=$(command head -c 24 /dev/urandom | base64 | command tr -d '/+=\n' | command head -c 24)
		if [[ -z "$GATEWAY_DB_PASSWORD" || "$GATEWAY_DB_PASSWORD" == *[!A-Za-z0-9]* ]]; then
			note_fail "could not generate a database password"
			exit 1
		fi
		# Quoted identifier and literal, and alphanumerics only, so the value needs no
		# escaping in SQL and none in the DSN URL it is pasted into below.
		sudo -u postgres psql -q -c \
			"ALTER ROLE \"$AQUA_USER\" WITH PASSWORD '$GATEWAY_DB_PASSWORD'"
		record_credential "${AQUA_USER}_db" "$GATEWAY_DB_PASSWORD"
		ok "set a password for database role '$AQUA_USER'"
	else
		skip "database role '$AQUA_USER' already has a password"
	fi

	# Migrations are ordered and idempotent (CREATE ... IF NOT EXISTS throughout),
	# so replaying them is safe.
	# Migrations run AS the service user, deliberately.
	#
	# Running them as `postgres` would leave the tables owned by `postgres`, and the
	# gateway later needs to `CREATE TABLE ... PARTITION OF events` at each month
	# boundary. Creating a partition requires ownership of the parent table, so the
	# gateway would fail on the 1st of the month with a permission error — a bug that
	# would only appear weeks after the install.
	#
	# `pg_database_owner` owns the public schema on PostgreSQL 15+, and the `aqua` role
	# owns this database, so it can create here.
	local migration
	for migration in "$REPO_ROOT"/gateway/migrations/*.sql; do
		sudo -u "$AQUA_USER" psql -q -d aqua -f "$migration" >/dev/null
		ok "applied $(basename "$migration")"
	done

	# Belt and braces: the schema owner can already do everything, but explicit grants
	# survive a later migration being applied by a different role.
	sudo -u postgres psql -q -d aqua -c \
		"GRANT ALL ON ALL TABLES IN SCHEMA public TO $AQUA_USER;
		 GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO $AQUA_USER;
		 GRANT ALL ON ALL FUNCTIONS IN SCHEMA public TO $AQUA_USER;" >/dev/null
	ok "granted privileges to $AQUA_USER"

	# Confirm the tuning actually took effect rather than being silently ignored.
	local shared_buffers
	shared_buffers=$(sudo -u postgres psql -tAc "SHOW shared_buffers")
	ok "shared_buffers = ${shared_buffers}"
}

# =============================================================================
# 5. Mosquitto
# =============================================================================
configure_mosquitto() {
	section "Mosquitto"

	install -D -m 0644 "$REPO_ROOT/deploy/mosquitto/aqua.conf" \
		/etc/mosquitto/conf.d/aqua.conf

	# Per-node credentials. `-c` would clobber an existing file on every re-run, so
	# only create when absent and append new users otherwise.
	if [[ ! -f /etc/mosquitto/passwd ]]; then
		# Only the first user may create the file; see the note on `-c` below.
		local create_flag="-c"
		for user in od_sensor aerator mixer pump gateway; do
			local secret
			# `command head`, not `head`: this script's output helpers live in the
			# same namespace, and a helper named `head` once shadowed the binary
			# here. The "random" credential became the literal text of a section
			# header -- the same value on every host, and with newlines in it the
			# next mosquitto_passwd killed the install silently under `set -e`.
			secret=$(command head -c 24 /dev/urandom | base64 | command tr -d '/+=\n' | command head -c 24)
			if [[ -z "$secret" || "$secret" == *[!A-Za-z0-9]* ]]; then
				note_fail "credential generation for $user produced: $(printf '%q' "$secret")"
				exit 1
			fi
			# `-c` means "create the file", and it OVERWRITES one that already exists.
			# It may therefore be used for the first user only. Using it on every
			# iteration -- as this loop once did -- left just `gateway` in the file:
			# each node user was created and then deleted by the next pass. The script
			# printed five credentials, four of which were already invalid, and the only
			# symptom was `[code:135] Not authorized` on a freshly flashed node.
			mosquitto_passwd -b $create_flag /etc/mosquitto/passwd "$user" "$secret"
			create_flag=""
			record_credential "$user" "$secret"
			printf '  credential  %-10s %s\n' "$user" "$secret"

			# Kept so install_gateway can put the broker's own credential where the
			# gateway reads it. Without this the gateway boots with the template's
			# CHANGE_ME, and since mosquitto has `allow_anonymous false` it dies in a
			# reconnect loop reporting only `[code:135] Not authorized`: a fresh install
			# that cannot work until somebody transcribes a value out of the scrollback.
			if [[ "$user" == "gateway" ]]; then
				GATEWAY_MQTT_SECRET="$secret"
			fi
		done
		chown mosquitto:mosquitto /etc/mosquitto/passwd
		chmod 0600 /etc/mosquitto/passwd

		# Prove the file holds every user rather than trusting the loop above. Missing
		# users are otherwise only discovered when a node fails to connect, which looks
		# like a firmware problem and is not one.
		local present
		present=$(awk -F: '{printf "%s ", $1}' /etc/mosquitto/passwd)
		local absent=""
		for user in od_sensor aerator mixer pump gateway; do
			[[ " $present" == *"$user "* ]] || absent="$absent $user"
		done
		if [[ -n "$absent" ]]; then
			note_fail "broker password file is missing users:$absent (it has: $present)"
		else
			ok "broker users: $present"
		fi

		yellow "  ^ also saved to $CREDENTIALS_FILE (root-only); a node needs its own"
		yellow "    credential compiled into the firmware, it cannot fetch it later"
	else
		skip "/etc/mosquitto/passwd exists (leaving credentials untouched)"
	fi

	install -d -o mosquitto -g mosquitto -m 0755 /var/lib/mosquitto

	# Debian's own mosquitto.conf ships `log_dest file /var/log/mosquitto/mosquitto.log`,
	# and `log_dest` ACCUMULATES rather than overrides -- so `log_dest stderr` in
	# conf.d/aqua.conf does not replace it, it adds a second destination. The broker
	# would go on writing every connection and notice to the SD card, defeating the
	# journald-to-RAM change and the write-rate budget that depends on it. There is no
	# way to remove a destination from an included file, so the line is neutralised in
	# place and the modification is idempotent (a commented line does not match again).
	if grep -qE '^[[:space:]]*log_dest[[:space:]]+file' /etc/mosquitto/mosquitto.conf; then
		cp -a /etc/mosquitto/mosquitto.conf /etc/mosquitto/mosquitto.conf.aqua-orig
		sed -i -E 's|^([[:space:]]*log_dest[[:space:]]+file.*)$|# \1|' /etc/mosquitto/mosquitto.conf
		ok "disabled mosquitto's file log destination (stderr via journald instead)"
	fi

	systemctl enable --now mosquitto
	systemctl restart mosquitto

	# Same lesson as the PostgreSQL step: `systemctl restart` returning is not the
	# broker running. A configuration error here is reported by mosquitto on stderr and
	# the unit exits 3, so without this check the next thing to notice is a node that
	# cannot connect -- much later and much further from the cause.
	if ! systemctl is-active --quiet mosquitto; then
		note_fail "mosquitto is not running after restart"
		systemctl --no-pager -l status mosquitto 2>&1 | tail -12 || true
		printf '\n'
		journalctl -u mosquitto -n 20 --no-pager 2>&1 || true
		exit 1
	fi
	ok "broker listening on 1883"
}

# =============================================================================
# 6. Gateway
# =============================================================================
install_gateway() {
	section "Gateway"

	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$INSTALL_ROOT"
	# `--delete-excluded` is the point, not a detail. Plain `--delete` with `--exclude`
	# leaves an excluded directory in place, so a stale `aqua_gateway/orchestration/__pycache__`
	# in the destination makes rsync refuse to remove its parent ("cannot delete non-empty
	# directory: aqua_gateway/orchestration") and the source's *code* changes can silently
	# fail to land -- which is how a deploy once shipped a gateway missing the exact
	# `orchestration/` module that had just changed. Deleting the excluded cruft too is what
	# makes the destination a faithful copy of the source.
	rsync -a --delete --delete-excluded \
		--exclude '.venv' --exclude '__pycache__' --exclude '.pytest_cache' \
		"$REPO_ROOT/gateway/" "$INSTALL_ROOT/gateway/"
	rsync -a --delete "$REPO_ROOT/docs/" "$INSTALL_ROOT/docs/"
	# `gateway/tests/test_env_template.py` reads the template from the repository
	# root, two levels above the test file, so without this copy the deployed tree
	# cannot run its own suite -- which is how a deployment is verified. The omission
	# is invisible until someone runs the tests on the host and gets a FileNotFoundError
	# that looks like a broken test rather than a missing file.
	install -o "$AQUA_USER" -g "$AQUA_USER" -m 0644 \
		"$REPO_ROOT/.env.example" "$INSTALL_ROOT/.env.example"
	# Same omission, second site: `tests/test_sample_time_and_unknowns.py` loads
	# `tools/mqtt-simulator.py` (via `parents[2]`) to assert that a batch of simulated
	# samples keeps its own device stamps. Not deploying `tools/` cost three failures on
	# the Pi with `FileNotFoundError: .../tools/mqtt-simulator.py` -- again reading as a
	# broken test rather than a missing file. Only the simulator is needed, so the rest of
	# `tools/` stays out of the production tree.
	install -d -o "$AQUA_USER" -g "$AQUA_USER" -m 0755 "$INSTALL_ROOT/tools"
	install -o "$AQUA_USER" -g "$AQUA_USER" -m 0644 \
		"$REPO_ROOT/tools/mqtt-simulator.py" "$INSTALL_ROOT/tools/mqtt-simulator.py"
	chown -R "$AQUA_USER:$AQUA_USER" "$INSTALL_ROOT"
	ok "synchronised to $INSTALL_ROOT"

	if [[ ! -d "$INSTALL_ROOT/gateway/.venv" ]]; then
		sudo -u "$AQUA_USER" python3 -m venv "$INSTALL_ROOT/gateway/.venv"
		ok "created virtualenv"
	fi
	# Install only when the dependency set actually changed. `pip install -e` is cheap when
	# everything is satisfied, but the Pi's network is not: with no wheel cache it re-consults
	# PyPI for each package and a flaky link turns that into minutes of retries -- which reads
	# as "the installer hung". A sentinel keyed on `pyproject.toml`'s hash skips the whole step
	# on an unchanged tree, so a re-run is seconds, not minutes. `--upgrade pip` is also gone:
	# it re-downloaded pip on every run for no benefit once the venv exists.
	VENV="$INSTALL_ROOT/gateway/.venv"
	PYPROJECT_HASH=$(sha256sum "$INSTALL_ROOT/gateway/pyproject.toml" | cut -d' ' -f1)
	SENTINEL="$VENV/.deps-ok"
	if [[ "$(cat "$SENTINEL" 2>/dev/null)" == "$PYPROJECT_HASH" ]]; then
		ok "gateway dependencies unchanged (skipping pip)"
	else
		sudo -u "$AQUA_USER" "$VENV/bin/pip" install --quiet --upgrade pip
		sudo -u "$AQUA_USER" "$VENV/bin/pip" install --quiet -e "$INSTALL_ROOT/gateway"
		echo "$PYPROJECT_HASH" | sudo -u "$AQUA_USER" tee "$SENTINEL" >/dev/null
		ok "installed aqua-gateway"
	fi

	if [[ ! -f "$CONF_ROOT/gateway.env" ]]; then
		install -m 0640 -o "$AQUA_USER" -g "$AQUA_USER" "$REPO_ROOT/.env.example" "$CONF_ROOT/gateway.env"
		note_warn "created $CONF_ROOT/gateway.env from the template — fill in the storage credentials"
	fi

	# The gateway has to authenticate to the broker this installer just configured, so
	# its credential is written in rather than left for a human to copy. The node
	# credentials stay print-only: they belong in firmware config, not on this host.
	if [[ -n "${GATEWAY_MQTT_SECRET:-}" ]]; then
		sed -i "s|^AQUA_MQTT__PASSWORD=.*|AQUA_MQTT__PASSWORD=${GATEWAY_MQTT_SECRET}|" "$CONF_ROOT/gateway.env"
		# sed -i replaces the file, so the ownership set by `install` is reapplied.
		chown "$AQUA_USER:$AQUA_USER" "$CONF_ROOT/gateway.env"
		chmod 0640 "$CONF_ROOT/gateway.env"
		ok "wrote the gateway's broker credential into $CONF_ROOT/gateway.env"
	elif grep -qE '^AQUA_MQTT__PASSWORD=(CHANGE_ME)?$' "$CONF_ROOT/gateway.env"; then
		# Reachable when /etc/mosquitto/passwd already exists from an earlier run, so
		# no secret was generated now and the real one cannot be recovered from a hash.
		# Better to say so than to leave the gateway looping on "Not authorized".
		note_fail "gateway.env still holds the placeholder MQTT password while /etc/mosquitto/passwd exists; the gateway cannot authenticate"
		printf '  recover with:\n'
		printf '    sudo mosquitto_passwd -b /etc/mosquitto/passwd gateway <new-secret>\n'
		printf '    sudo sed -i \"s|^AQUA_MQTT__PASSWORD=.*|AQUA_MQTT__PASSWORD=<new-secret>|\" %s\n' "$CONF_ROOT/gateway.env"
		printf '    sudo systemctl restart aqua-gateway\n'
	fi

	if [[ -n "${GATEWAY_DB_PASSWORD:-}" ]]; then
		# `?sslmode=disable` because asyncpg's TLS path reads a client certificate from
		# ~/.postgresql/, which this unit's ProtectHome=true makes unreadable; the EACCES
		# aborts the connection and is reported as a permission error on that file, which
		# names neither TLS nor the real cause. Loopback needs no TLS anyway.
		sed -i "s|^AQUA_DATABASE_URL=.*|AQUA_DATABASE_URL=postgresql://${AQUA_USER}:${GATEWAY_DB_PASSWORD}@127.0.0.1:5432/aqua?sslmode=disable|" \
			"$CONF_ROOT/gateway.env"
		chown "$AQUA_USER:$AQUA_USER" "$CONF_ROOT/gateway.env"
		chmod 0640 "$CONF_ROOT/gateway.env"
		ok "wrote the database DSN into $CONF_ROOT/gateway.env"
	elif ! grep -qE '^AQUA_DATABASE_URL=postgresql://[^:@]+:[^@]+@' "$CONF_ROOT/gateway.env"; then
		note_fail "gateway.env has no password in AQUA_DATABASE_URL while pg_hba requires scram-sha-256 over TCP; the gateway cannot authenticate"
		printf '  recover with:\n'
		printf '    sudo -u postgres psql -c "ALTER ROLE %s WITH PASSWORD %%s"   # pick a password\n' "$AQUA_USER"
		printf '    then set AQUA_DATABASE_URL=postgresql://%s:<password>@127.0.0.1:5432/aqua\n' "$AQUA_USER"
		printf '    in %s and restart aqua-gateway\n' "$CONF_ROOT/gateway.env"
	fi

	# The long-running gateway, plus rotate/flush services and their timers, plus
	# the Caddy bind-refresh pair. Kept as separate files rather than heredocs so
	# the scheduled units are reviewable in the repo like everything else.
	#
	# The helper `.sh` is installed executable, separate from the units: a blanket
	# `install -m 0644` would drop its exec bit and the unit would fail at start
	# with 203/EXEC the first time it ran — which, being a background timer, is a
	# failure nobody sees until the address has already changed.
	local unit
	install -d -m 0755 "$INSTALL_ROOT/deploy/systemd"
	for unit in "$REPO_ROOT"/deploy/systemd/*; do
		case "$unit" in
		*.sh)
			install -m 0755 "$unit" "$INSTALL_ROOT/deploy/systemd/"
			install -m 0755 "$unit" /etc/systemd/system/
			;;
		*)
			install -m 0644 "$unit" /etc/systemd/system/
			;;
		esac
	done
	ok "installed $(basename -a "$REPO_ROOT"/deploy/systemd/* | tr '\n' ' ')"

	systemctl daemon-reload
	ok "systemd units installed"
}

# =============================================================================
# 7. Caddy and the dashboard
# =============================================================================
configure_caddy() {
	section "Caddy / web"

	# Fill in this host's own LAN address before installing the config. The Caddyfile ships
	# a literal `@LAN_IP@` because `bind` needs an address and the right one is a property of
	# *this* machine, not of the repo. Shipping a literal meant the config carried the
	# author's IP: Caddy then died with `bind: cannot assign requested address` on any host
	# whose address differed, and DHCP guarantees that eventually.
	local lan_ip
	lan_ip="$(hostname -I 2>/dev/null | tr ' ' '\n' | grep -vE '^(127\.|100\.|::)' | head -1)"
	if [[ -z "$lan_ip" ]]; then
		note_warn "no LAN address found; leaving Caddy's bind at 127.0.0.1 (dashboard LAN-only)"
		lan_ip="127.0.0.1"
	fi
	sed -e "s/@LAN_IP@/$lan_ip/" "$REPO_ROOT/deploy/caddy/Caddyfile" > /etc/caddy/Caddyfile
	chmod 0644 /etc/caddy/Caddyfile
	ok "caddy bound to LAN address $lan_ip"

	install -d -o caddy -g caddy -m 0755 "$WEB_ROOT"

	# Build the dashboard here when Node is available, so `install.sh` cannot deploy a
	# stale `web/out/`. This is the whole problem it fixes: the script only ever *copied*
	# `web/out/`, so re-running it on a source tree whose `out/` was built days ago shipped
	# the old JS over the top of a correct one -- and the symptom (buttons inert, controls
	# missing) looks like a code bug, not a stale artifact. When npm is absent the tree is
	# built elsewhere; then we refuse to deploy an `out/` older than the sources rather than
	# silently serve it.
	if command -v npm >/dev/null 2>&1 && [[ -f "$REPO_ROOT/web/package.json" ]]; then
		warn "building dashboard (npm run build in web/)"
		if ( cd "$REPO_ROOT/web" && npm run build >/dev/null 2>&1 ); then
			ok "dashboard built"
		else
			note_warn "dashboard build failed; deploying existing web/out/ if present"
		fi
	fi

	if [[ -f "$REPO_ROOT/web/out/index.html" ]]; then
		# Refuse a stale artifact: if any source file is newer than the built index, the
		# `out/` does not reflect the code and deploying it would be a lie the operator
		# cannot see. Warn loudly instead of quietly shipping it.
		if find "$REPO_ROOT/web/src" -newer "$REPO_ROOT/web/out/index.html" -name '*.tsx' -print -quit 2>/dev/null | grep -q .; then
			note_warn "web/out/ is OLDER than web/src/ -- deploying anyway; run 'npm run build' in web/ to refresh"
		fi
		rsync -a --delete "$REPO_ROOT/web/out/" "$WEB_ROOT/"
		ok "dashboard deployed to $WEB_ROOT"
	else
		note_warn "web/out/ not built — run 'npm run build' in web/ (output: 'export')"
		printf '         the browser does all rendering, so no Node runtime is needed HERE,\n'
		printf '         only on the build machine.\n'
	fi

	systemctl enable --now caddy
	systemctl reload caddy || systemctl restart caddy
	ok "caddy active"
}

# =============================================================================
# 8. Start services
# =============================================================================
start_services() {
	section "Services"

	systemctl enable aqua-gateway.service
	systemctl enable aqua-flush.timer
	systemctl enable aqua-rotate.timer
	# Keeps Caddy's LAN `bind` pointed at the address the board actually has. The
	# installer writes it once from this host's address; DHCP does not promise the
	# same one twice, and when they disagree Caddy cannot bind and stops while
	# every other unit still reports healthy.
	systemctl enable aqua-fix-caddy-ip.timer

	systemctl restart aqua-gateway.service
	systemctl restart aqua-flush.timer aqua-rotate.timer
	systemctl start aqua-fix-caddy-ip.timer

	sleep 3

	local failed=0
	for unit in postgresql mosquitto caddy aqua-gateway; do
		if systemctl is-active --quiet "$unit"; then
			ok "$unit active"
		else
			note_fail "$unit is not active"
			failed=1
		fi
	done

	if ((failed)); then
		printf '\n  inspect with:  journalctl -u aqua-gateway -n 50 --no-pager\n'
	fi

	for timer in aqua-flush.timer aqua-rotate.timer aqua-fix-caddy-ip.timer; do
		if systemctl is-active --quiet "$timer"; then
			ok "$timer armed"
		else
			note_warn "$timer not active"
		fi
	done
}

# =============================================================================
# 9. Post-install verification
# =============================================================================
verify() {
	section "Verification"

	printf '  listening sockets (expect 1883, 5432, 8000 loopback, 80/443 LAN):\n'
	ss -tlnp 2>/dev/null | awk 'NR==1 || /LISTEN/' | sed 's/^/    /'

	if curl -fsS --max-time 5 http://127.0.0.1:8000/healthz >/dev/null 2>&1; then
		ok "gateway /healthz responds"
	else
		note_warn "gateway /healthz did not respond yet"
	fi

	if curl -fsS --max-time 5 -o /dev/null http://127.0.0.1:1883 2>/dev/null; then
		ok "broker port open"
	else
		ok "broker port open (not HTTP, as expected)"
	fi

	printf '\n  HAT hardware & sensors:\n'
	if command -v i2cdetect >/dev/null 2>&1 && [[ -e /dev/i2c-1 ]]; then
		local i2c_scan
		i2c_scan=$(i2cdetect -y 1 2>/dev/null || true)
		if echo "$i2c_scan" | grep -qE "( 68| UU)"; then
			ok "DS3231 RTC detected at 0x68 (or claimed by kernel driver)"
		else
			note_warn "DS3231 RTC not detected at 0x68 on I2C bus 1"
		fi
		if echo "$i2c_scan" | grep -q " 40"; then
			ok "INA226 (Vin / Entrada) detected at 0x40"
		else
			note_warn "INA226 (Vin / Entrada) not detected at 0x40"
		fi
		if echo "$i2c_scan" | grep -q " 41"; then
			ok "INA226 (5V Out / Salida) detected at 0x41"
		else
			note_warn "INA226 (5V Out / Salida) not detected at 0x41"
		fi
	else
		skip "i2cdetect or /dev/i2c-1 not available (normal in non-Pi environments)"
	fi

	# Report the number retention depends on.
	printf '\n  disk: %s\n' "$(df -h / | tail -1 | awk '{print $4" free of "$2}')"
	printf '  archive: %s\n' "$(du -sh "$DATA_ROOT" 2>/dev/null | cut -f1 || echo 'empty')"

	printf '\n  baseline SD writes (takes 30s, this is the number to watch):\n'
	local a b
	a=$(awk '{print $7}' /sys/block/mmcblk0/stat)
	sleep 30
	b=$(awk '{print $7}' /sys/block/mmcblk0/stat)
	local bytes=$(((b - a) * 512))
	printf '    %d bytes in 30s (~%d MB/day extrapolated)\n' "$bytes" "$((bytes * 2880 / 1024 / 1024))"
	if ((bytes * 2880 / 1024 / 1024 > 60)); then
		note_warn "idle writes still high — check journald and rsyslog"
	else
		ok "idle writes look healthy"
	fi
}

# =============================================================================
main() {
	printf '\n\033[1mAquaControl station install\033[0m\n'
	printf 'repo: %s\n' "$REPO_ROOT"

	preflight
	install_packages
	host_hygiene
	create_directories
	configure_postgres
	configure_mosquitto
	install_gateway
	configure_caddy
	start_services
	verify

	section "Summary"
	if ((FAILURES == 0)); then
		green "install completed with $WARNINGS warning(s)"
	else
		alert "install completed with $FAILURES failure(s) and $WARNINGS warning(s)"
	fi
	printf '\nNext:\n'
	printf '  1. Node credentials are in %s (root-only). Back that file up;\n' "$CREDENTIALS_FILE"
	printf '     each node needs its own credential compiled into its firmware.\n'
	printf '  2. In the Supabase dashboard: create the %s bucket, generate its\n' "aqua-archive"
	printf '     Storage S3 keys (Storage -> S3 Access Keys) and put them in\n'
	printf '     /etc/aqua/gateway.env. Project API keys will not work here.\n'
	printf '  3. Apply the firmware patches in firmware-patches/ and reflash nodes.\n'
	printf '  4. Read docs/RUNBOOK.md before the first experiment.\n\n'

	exit $((FAILURES > 0))
}

main "$@"
